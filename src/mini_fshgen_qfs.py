def parse_gid(text: str) -> int:
    value = text.strip().lower()

    if value.startswith("0x"):
        value = value[2:]

    if (
        not value
        or len(value) > 8
        or any(
            char not in "0123456789abcdef"
            for char in value
        )
    ):
        raise ValueError(
            f"invalid 32-bit GID: {text}"
        )

    return int(
        value,
        16,
    )


def make_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Experimental Python-only BAT subset "
            "of memo33/fshgen"
        )
    )

    subparsers = parser.add_subparsers(
        dest="command",
        required=True,
    )

    importer = subparsers.add_parser(
        "import",
        help=(
            "convert BAT OBJ/PNG files into "
            "a DBPF/SC4Model"
        ),
    )

    importer.add_argument(
        "-o",
        "--output",
        type=Path,
        required=True,
    )

    importer.add_argument(
        "-f",
        "--force",
        action="store_true",
    )

    importer.add_argument(
        "--with-BAT-models",
        dest="with_bat_models",
        action="store_true",
    )

    importer.add_argument(
        "--format",
        default="Dxt1",
    )

    importer.add_argument(
        "--gid",
        required=True,
    )

    importer.add_argument(
        "inputs",
        nargs="+",
    )

    return parser


def main(
    argv: Sequence[str] | None = None,
) -> int:
    parser = make_parser()
    args = parser.parse_args(argv)

    try:
        if args.command == "import":
            gid = parse_gid(
                args.gid
            )

            inputs = expand_inputs(
                args.inputs
            )

            import_files(
                output=args.output,
                gid=gid,
                input_paths=inputs,
                force=args.force,
                with_bat_models=args.with_bat_models,
                image_format=args.format,
            )

            return 0

        parser.error(
            f"unknown command: {args.command}"
        )

    except Exception as exc:
        print(
            f"mini_fshgen: error: {exc}",
            file=sys.stderr,
        )
        return 1

    return 2


if __name__ == "__main__":
    raise SystemExit(
        main()
    )
