# Import command
# ---------------------------------------------------------------------------

def import_files(
    output: Path,
    gid: int,
    input_paths: Sequence[Path],
    *,
    force: bool,
    with_bat_models: bool,
    image_format: str,
) -> None:
    if image_format.lower() != "dxt1":
        raise ValueError(
            "mini_fshgen currently supports only --format Dxt1"
        )

    if (
        output.exists()
        and not force
    ):
        raise FileExistsError(
            f"output already exists; use --force: {output}"
        )

    entries: list[DbpfEntry] = []

    for path in input_paths:
        if not path.is_file():
            print(
                f"File {path} does not exist and has been skipped",
                file=sys.stderr,
            )
            continue

        suffix = path.suffix.lower()

        iid = extract_last_iid(
            path.name
        )

        if suffix == ".obj":
            if not with_bat_models:
                print(
                    f"warning: OBJ skipped without --with-BAT-models: {path}",
                    file=sys.stderr,
                )
                continue

            print(
                f"OBJ -> S3D  IID=0x{iid:08X}: {path}"
            )

            entries.append(
                DbpfEntry(
                    tid=TID_S3D,
                    gid=gid,
                    iid=iid,
                    data=encode_s3d(
                        path,
                        iid,
                    ),
                )
            )

        elif suffix in (
            ".png",
            ".bmp",
        ):
            print(
                f"image -> FSH IID=0x{iid:08X}: {path}"
            )

            entries.append(
                DbpfEntry(
                    tid=TID_FSH,
                    gid=gid,
                    iid=iid,
                    data=encode_fsh_dxt1(
                        path
                    ),
                )
            )

        elif (
            suffix == ".mtl"
            and with_bat_models
        ):
            continue

        else:
            print(
                f"warning: unsupported input skipped: {path}",
                file=sys.stderr,
            )

    if not entries:
        raise RuntimeError(
            "no supported input files were converted"
        )

    entries.sort(
        key=lambda entry: (
            entry.tid,
            entry.gid,
            entry.iid,
        )
    )

    write_dbpf(
        output,
        entries,
    )

    print(
        f"Wrote {output} with "
        f"{len(entries)} source DBPF entries."
    )


