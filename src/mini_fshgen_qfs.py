def material_iid(base_iid: int, index: int) -> int:
    """
    BAT material/tile IID mapping.

    Supports up to 1024 materials, matching the bit allocation used by the BAT
    model convention.
    """
    if not 0 <= index < 1024:
        raise ValueError(
            "S3D model must have fewer than 1024 materials"
        )

    offset = (
        ((index & 0x0380) << 5)
        | ((index & 0x0040) << 5)
        | ((index & 0x0030) << 2)
        | (index & 0x000F)
    )

    return (base_iid + offset) & 0xFFFFFFFF


@dataclass
class S3dMesh:
    name: str | None
    material_name: str | None
    material_iid: int
    vertices: list[tuple[float, float, float, float, float]]
    indices: list[int]


def convert_obj_meshes(
    model: ObjModel,
    base_iid: int,
) -> list[S3dMesh]:
    result: list[S3dMesh] = []

    for mesh_index, mesh in enumerate(model.meshes):
        refs: list[ObjRef] = []
        lookup: dict[ObjRef, int] = {}

        for face in mesh.faces:
            for ref in face:
                if ref not in lookup:
                    lookup[ref] = len(refs)
                    refs.append(ref)

        verts: list[
            tuple[float, float, float, float, float]
        ] = []

        for ref in refs:
            x, y, z = model.vertices[ref.vertex]
            tex_u, tex_v = model.texcoords[ref.texcoord]

            # Default fshgen OBJ conversion reverses V.
            verts.append(
                (
                    x,
                    y,
                    z,
                    tex_u,
                    1.0 - tex_v,
                )
            )

        indices: list[int] = []

        for face in mesh.faces:
            indices.extend(
                lookup[ref]
                for ref in face
            )

        if len(verts) > 0xFFFF:
            raise ValueError(
                "S3D vertex group exceeds 65535 vertices"
            )

        if len(indices) > 0xFFFF:
            raise ValueError(
                "S3D index group exceeds 65535 indices"
            )

        result.append(
            S3dMesh(
                name=mesh.object_name,
                material_name=mesh.material or None,
                material_iid=material_iid(
                    base_iid,
                    mesh_index,
                ),
                vertices=verts,
                indices=indices,
            )
        )

    return result


def encode_vert_group(mesh: S3dMesh) -> bytes:
    out = bytearray()

    out += u16(0)
    out += u16(len(mesh.vertices))
    out += u32(VERT_FORMAT)

    for vertex in mesh.vertices:
        for value in vertex:
            out += f32(value)

    return bytes(out)


def encode_indx_group(mesh: S3dMesh) -> bytes:
    out = bytearray()

    out += u16(0)
    out += u16(INDX_STRIDE)
    out += u16(len(mesh.indices))

    for index in mesh.indices:
        out += u16(index)

    return bytes(out)


def encode_prim_group(num_indices: int) -> bytes:
    """
    One Triangle primitive spanning the entire index group.
    """
    return (
        u16(1)
        + u32(PRIM_TRIANGLE)
        + u32(0)
        + u32(num_indices)
    )


def encode_mats_group(mesh: S3dMesh) -> bytes:
    flags = (
        MATS_ALPHA_TEST
        | MATS_DEPTH_TEST
        | MATS_BACKFACE_CULLING
        | MATS_TEXTURING
    )

    out = bytearray()

    out += u32(flags)

    out += bytes(
        (
            MATS_FUNC_GREATER,
            MATS_FUNC_LESS_EQUAL,
            MATS_BLEND_ONE,
            MATS_BLEND_ZERO,
        )
    )

    out += i16(0x7FFF)
    out += u32(0)
    out += b"\x00"

    # Number of material records.
    out += b"\x01"

    out += u32(mesh.material_iid)

    out += bytes(
        (
            WRAP_REPEAT,
            WRAP_REPEAT,
            MAG_NEAREST,
            MIN_NEAREST_NO_MIPMAP,
        )
    )

    out += i16(0)
    out += i16(0)

    out += named_string(
        mesh.material_name,
        short=False,
    )

    return bytes(out)


def encode_anim_group(
    mesh_index: int,
    prim_index: int,
    name: str | None,
) -> bytes:
    out = bytearray()

    out += named_string(
        name,
        short=True,
    )

    out += u16(mesh_index)
    out += u16(mesh_index)
    out += u16(prim_index)
    out += u16(mesh_index)

    return bytes(out)


def generic_section(
    signature: bytes,
    groups: Sequence[bytes],
) -> bytes:
    body = (
        u32(len(groups))
        + b"".join(groups)
    )

    return (
        signature
        + u32(8 + len(body))
        + body
    )


def encode_s3d(
    obj_path: Path,
    iid: int,
) -> bytes:
    """
    Convert one restricted BAT OBJ file to S3D v1.5.
    """
    model = parse_obj(obj_path)
    meshes = convert_obj_meshes(
        model,
        iid,
    )

    vert_groups = [
        encode_vert_group(mesh)
        for mesh in meshes
    ]

    indx_groups = [
        encode_indx_group(mesh)
        for mesh in meshes
    ]

    mats_groups = [
        encode_mats_group(mesh)
        for mesh in meshes
    ]

    # PRIM groups can be shared when index counts match.
    prim_sizes: list[int] = []
    prim_index_by_size: dict[int, int] = {}

    for mesh in meshes:
        size = len(mesh.indices)

        if size not in prim_index_by_size:
            prim_index_by_size[size] = len(prim_sizes)
            prim_sizes.append(size)

    prim_groups = [
        encode_prim_group(size)
        for size in prim_sizes
    ]

    anim_groups = [
        encode_anim_group(
            mesh_index=index,
            prim_index=prim_index_by_size[
                len(mesh.indices)
            ],
            name=mesh.name,
        )
        for index, mesh in enumerate(meshes)
    ]

    head = (
        b"HEAD"
        + u32(12)
        + u16(1)
        + u16(5)
    )

    vert = generic_section(
        b"VERT",
        vert_groups,
    )

    indx = generic_section(
        b"INDX",
        indx_groups,
    )

    prim = generic_section(
        b"PRIM",
        prim_groups,
    )

    mats = generic_section(
        b"MATS",
        mats_groups,
    )

    anim_body = bytearray()

    anim_body += u16(1)
    anim_body += u16(0)
    anim_body += u16(PLAYMODE_LOOPING)
    anim_body += u32(0)
    anim_body += f32(0)
    anim_body += u16(len(anim_groups))
    anim_body += b"".join(anim_groups)

    anim = (
        b"ANIM"
        + u32(8 + len(anim_body))
        + bytes(anim_body)
    )

    prop = generic_section(
        b"PROP",
        [],
    )

    regp = generic_section(
        b"REGP",
        [],
    )

    body = (
        head
        + vert
        + indx
        + prim
        + mats
        + anim
        + prop
        + regp
    )

    return (
        b"3DMD"
        + u32(8 + len(body))
        + body
    )


