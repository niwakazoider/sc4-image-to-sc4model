# PNG/BMP -> FSH
# ---------------------------------------------------------------------------

def encode_fsh_dxt1(
    image_path: Path,
) -> bytes:
    image = Image.open(
        image_path
    ).convert("RGBA")

    width, height = image.size

    dxt_data = encode_dxt1(
        image
    )

    element_size = (
        0x10
        + len(dxt_data)
    )

    element_offset = 0x18

    total_size = (
        0x10
        + 8
        + element_size
    )

    out = bytearray()

    out += b"SHPI"
    out += u32(total_size)
    out += u32(1)

    # fshgen default directory ID is G264.
    out += b"G264"

    out += b"BMP1"
    out += u32(element_offset)

    # High 24 bits contain element size.
    # Low byte 0x60 is DXT1.
    out += u32(
        (element_size << 8)
        | 0x60
    )

    out += u16(width)
    out += u16(height)

    out += u16(0)
    out += u16(0)
    out += u16(0)
    out += u16(0)

    out += dxt_data

    if len(out) != total_size:
        raise AssertionError(
            (
                len(out),
                total_size,
            )
        )

    return bytes(out)



# ---------------------------------------------------------------------------
# QFS / RefPack compression
# ---------------------------------------------------------------------------

def _highest_one_bit(value: int) -> int:
    if value <= 0:
        return 0
    return 1 << (value.bit_length() - 1)


class _QfsHash:
    """
    Hash-chain match finder corresponding to the compact QFS compressor used by
    scdbpf. The encoded stream format is the standard Maxis QFS/RefPack format
    used by SimCity 4 DBPF resources.
    """

    LOOK_AHEAD = 3

    def __init__(self, size_hint: int):
        self.window_size = min(
            0x20000,
            _highest_one_bit(size_hint),
        )
        self.window_mask = self.window_size - 1

        self.hash_size = min(
            0x10000,
            max(
                0x20,
                _highest_one_bit(size_hint) // 2,
            ),
        )
        self.hash_mask = self.hash_size - 1

        trailing_zeros = (
            self.hash_size.bit_length() - 1
        )
        self.hash_shift = (
            trailing_zeros + self.LOOK_AHEAD - 1
        ) // self.LOOK_AHEAD

        self.value = 0
        self.previous_positions = [0] * self.window_size
        self.head = [-1] * self.hash_size

    def update(self, byte_value: int) -> None:
        self.value = (
            (self.value << self.hash_shift)
            ^ (byte_value & 0xFF)
        ) & self.hash_mask

    def insert(self, position: int) -> None:
        slot = position & self.window_mask
        self.previous_positions[slot] = self.head[self.value]
        self.head[self.value] = position

    def previous(self, position: int) -> int:
        return self.previous_positions[
            position & self.window_mask
        ]


def qfs_is_compressed(data: bytes) -> bool:
    if len(data) < 9:
        return False

    magic = struct.unpack_from("<H", data, 4)[0]
    if magic != QFS_MAGIC:
        return False

    # Avoid treating an S3D whose bytes happen to match the QFS signature as
    # compressed, mirroring scdbpf's safeguard.
    return data[:4] != b"3DMD"


def qfs_decompressed_size(data: bytes) -> int | None:
    if not qfs_is_compressed(data):
        return None

    return (
        (data[6] << 16)
        | (data[7] << 8)
        | data[8]
    )


def qfs_decompress(data: bytes) -> bytes:
    """
    Small verifier/decompressor used by this prototype for self-checking the
    streams emitted by qfs_compress_raw().
    """
    expected = qfs_decompressed_size(data)
    if expected is None:
        return data

    src = 9
    out = bytearray()

    while src < len(data):
        control = data[src]
        src += 1

        if control >= 0xFC:
            plain = control & 0x03
            out += data[src:src + plain]
            src += plain
            break

        if control >= 0xE0:
            plain = ((control & 0x1F) << 2) + 4
            out += data[src:src + plain]
            src += plain
            continue

        if control >= 0xC0:
            if src + 3 > len(data):
                raise ValueError("truncated QFS 4-byte command")

            b1 = data[src]
            b2 = data[src + 1]
            b3 = data[src + 2]
            src += 3

            plain = control & 0x03
            copy_length = (
                ((control & 0x0C) << 6)
                + b3
                + 5
            )
            copy_offset = (
                ((control & 0x10) << 12)
                + (b1 << 8)
                + b2
            )

        elif control >= 0x80:
            if src + 2 > len(data):
                raise ValueError("truncated QFS 3-byte command")

            b1 = data[src]
            b2 = data[src + 1]
            src += 2

            plain = b1 >> 6
            copy_length = (
                (control & 0x3F)
                + 4
            )
            copy_offset = (
                ((b1 & 0x3F) << 8)
                + b2
            )

        else:
            if src >= len(data):
                raise ValueError("truncated QFS 2-byte command")

            b1 = data[src]
            src += 1

            plain = control & 0x03
            copy_length = (
                ((control >> 2) & 0x07)
                + 3
            )
            copy_offset = (
                ((control & 0x60) << 3)
                + b1
            )

        out += data[src:src + plain]
        src += plain

        copy_pos = (
            len(out)
            - copy_offset
            - 1
        )

        if copy_pos < 0:
            raise ValueError("invalid QFS copy offset")

        # QFS matches may overlap, so copy byte-by-byte.
        for _ in range(copy_length):
            out.append(out[copy_pos])
            copy_pos += 1

    if len(out) != expected:
        raise ValueError(
            "QFS decompression size mismatch: "
            f"expected {expected}, got {len(out)}"
        )

    return bytes(out)


def qfs_compress_raw(data: bytes) -> bytes:
    """
    Encode one QFS/RefPack stream.

    This is a Python port of the command selection used by memo33/scdbpf's
    QfsCompression implementation. It searches a 0x20000-byte maximum sliding
    window, supports matches from 3 to 1028 bytes, and limits hash-chain scans
    to 0x80 candidates.
    """
    source = bytes(data)
    source_size = len(source)

    if not (
        9 < source_size <= 0xFFFFFF
    ):
        return source

    LOOK_AHEAD = 3
    MIN_MATCH = 3
    MAX_MATCH = 1028
    MAX_ITER = 0x80

    finder = _QfsHash(source_size)
    max_distance = finder.window_size

    # Nine-byte header is filled after encoding.
    dest = bytearray(b"\x00" * 9)

    src_pos = 0

    finder.update(source[0])
    finder.update(source[1])
    finder.update(source[2])
    finder.insert(src_pos)

    def hash_update(position: int) -> None:
        finder.update(
            source[
                position + LOOK_AHEAD - 1
            ]
        )
        finder.insert(position)

    def common_prefix(
        match_pos: int,
        current_pos: int,
    ) -> int:
        length = 0
        max_length = min(
            MAX_MATCH,
            source_size - current_pos,
        )

        while (
            length < max_length
            and source[match_pos + length]
            == source[current_pos + length]
        ):
            length += 1

        return length

    def has_codepoint(
        offset: int,
        length: int,
    ) -> bool:
        return (
            (length >= 3 and offset < 1024)
            or (length >= 4 and offset < 0x4000)
            or (length >= 5 and offset < 0x20000)
        )

    def find_match(
        current_pos: int,
    ) -> tuple[int, int]:
        match_pos = finder.previous(current_pos)

        best_length = 0
        best_position = current_pos
        iteration = 0

        while (
            iteration <= MAX_ITER
            and match_pos >= 0
            and current_pos - match_pos <= max_distance
            and best_length < MAX_MATCH
            and current_pos + best_length < source_size
        ):
            if (
                best_length < 2
                or (
                    match_pos + best_length < current_pos
                    and source[match_pos + best_length]
                    == source[current_pos + best_length]
                    and source[match_pos + best_length - 1]
                    == source[current_pos + best_length - 1]
                )
                or (
                    match_pos + best_length >= current_pos
                    and source[match_pos + best_length]
                    == source[current_pos + best_length]
                    and source[match_pos + best_length - 1]
                    == source[current_pos + best_length - 1]
                )
            ):
                length = common_prefix(
                    match_pos,
                    current_pos,
                )
            else:
                length = 0

            offset = (
                current_pos
                - match_pos
                - 1
            )

            if (
                length > best_length
                and has_codepoint(
                    offset,
                    length,
                )
            ):
                best_length = min(
                    length,
                    MAX_MATCH,
                )
                best_position = match_pos

            match_pos = finder.previous(
                match_pos
            )
            iteration += 1

        return best_length, best_position

    def transfer_plain(
        start: int,
        length: int,
    ) -> None:
        if length > 0:
            dest.extend(
                source[start:start + length]
            )

    def encode(
        plain_length: int,
        copy_length: int,
        current_pos: int,
        match_position: int,
    ) -> None:
        """
        Encode pending literal bytes followed by an optional back-reference.
        """
        remaining_plain = plain_length

        while remaining_plain >= 4:
            chunk = min(
                remaining_plain & ~0x03,
                112,
            )

            dest.append(
                (chunk // 4) + 0xDF
            )

            start = (
                current_pos
                - remaining_plain
            )

            transfer_plain(
                start,
                chunk,
            )

            remaining_plain -= chunk

        if copy_length == 0:
            dest.append(
                0xFC + remaining_plain
            )

            if remaining_plain:
                start = (
                    current_pos
                    - remaining_plain
                )
                transfer_plain(
                    start,
                    remaining_plain,
                )

            return

        offset = (
            current_pos
            - match_position
            - 1
        )

        if (
            offset < 1024
            and 3 <= copy_length <= 10
        ):
            dest.append(
                ((offset >> 3) & 0x60)
                + ((copy_length - 3) * 4)
                + remaining_plain
            )
            dest.append(
                offset & 0xFF
            )

        elif (
            offset < 0x4000
            and 4 <= copy_length <= 67
        ):
            dest.append(
                0x80
                + (copy_length - 4)
            )
            dest.append(
                remaining_plain * 0x40
                + (offset >> 8)
            )
            dest.append(
                offset & 0xFF
            )

        elif (
            offset < 0x20000
            and 5 <= copy_length <= 1028
        ):
            dest.append(
                0xC0
                + ((offset >> 12) & 0x10)
                + (((copy_length - 5) >> 6) & 0x0C)
                + remaining_plain
            )
            dest.append(
                (offset >> 8) & 0xFF
            )
            dest.append(
                offset & 0xFF
            )
            dest.append(
                (copy_length - 5) & 0xFF
            )

        else:
            raise AssertionError(
                "no suitable QFS code point: "
                f"offset={offset}, "
                f"copy_length={copy_length}, "
                f"plain_length={remaining_plain}"
            )

        if remaining_plain:
            start = (
                current_pos
                - remaining_plain
            )
            transfer_plain(
                start,
                remaining_plain,
            )

    plain_start = src_pos

    while True:
        remaining = (
            source_size
            - src_pos
        )

        if remaining <= 3:
            src_pos = source_size

            encode(
                src_pos - plain_start,
                0,
                src_pos,
                src_pos,
            )
            break

        copy_length, match_position = find_match(
            src_pos
        )

        if copy_length < MIN_MATCH:
            src_pos += 1
            hash_update(src_pos)
            continue

        encode(
            src_pos - plain_start,
            copy_length,
            src_pos,
            match_position,
        )

        for _ in range(copy_length):
            src_pos += 1

            if (
                source_size - src_pos
                >= LOOK_AHEAD
            ):
                hash_update(src_pos)

        plain_start = src_pos

    compressed_size = len(dest)

    struct.pack_into(
        "<I",
        dest,
        0,
        compressed_size,
    )
    struct.pack_into(
        "<H",
        dest,
        4,
        QFS_MAGIC,
    )

    dest[6] = (
        source_size >> 16
    ) & 0xFF
    dest[7] = (
        source_size >> 8
    ) & 0xFF
    dest[8] = (
        source_size
    ) & 0xFF

    result = bytes(dest)

    # Verify our encoder before allowing the stream into a DBPF.
    if qfs_decompress(result) != source:
        raise AssertionError(
            "internal QFS round-trip verification failed"
        )

    return result


def qfs_compress(data: bytes) -> bytes:
    """
    Compress only when worthwhile.

    scdbpf requires the compressed stream to save more than 16 bytes, because
    every compressed DBPF entry adds a 16-byte row to the DIR resource.
    """
    source = bytes(data)

    if (
        len(source) <= 9
        or len(source) > 0xFFFFFF
        or qfs_is_compressed(source)
    ):
        return source

    compressed = qfs_compress_raw(
        source
    )

    if (
        compressed is not source
        and len(compressed)
        < len(source) - 16
    ):
        return compressed

    return source


def build_dir_resource(
    compressed_entries: Sequence["DbpfEntry"],
) -> bytes:
    """
    Build the SC4 DBPF DIR payload.

    Each record is:
        TID, GID, IID, decompressed_size
    as four little-endian uint32 values.
    """
    out = bytearray()

    for entry in compressed_entries:
        if entry.decompressed_size is None:
            continue

        out += struct.pack(
            "<IIII",
            entry.tid & 0xFFFFFFFF,
            entry.gid & 0xFFFFFFFF,
            entry.iid & 0xFFFFFFFF,
            entry.decompressed_size & 0xFFFFFFFF,
        )

    return bytes(out)



