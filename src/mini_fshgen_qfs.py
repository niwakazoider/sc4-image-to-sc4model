_ID_RE = re.compile(
    r"(?i)(?<![-0-9a-f])(?:0x)?([0-9a-f]{8}|0)(?=[_ .])"
)


def extract_last_iid(filename: str) -> int:
    """
    Extract the last absolute hexadecimal ID from a filename.

    The current BAT generator uses names such as:
      5ad0e817_ffffffff_00030000.obj
      00030000_Day.png
    """
    matches = list(_ID_RE.finditer(Path(filename).name))
    if not matches:
        raise ValueError(f"no hexadecimal IID found in filename: {filename}")
    return int(matches[-1].group(1), 16)


def expand_inputs(items: Sequence[str]) -> list[Path]:
    """
    Expand quoted wildcard arguments internally.

    This is convenient when invoked from subprocess without shell expansion:
      'output/*.obj'
      'output/*_Day.png'
    """
    result: list[Path] = []

    for item in items:
        if any(ch in item for ch in "*?["):
            found = sorted(Path(p) for p in glob.glob(item))
            if not found:
                print(
                    f"warning: pattern matched no files: {item}",
                    file=sys.stderr,
                )
            result.extend(found)
        else:
            result.append(Path(item))

    return result


