QFS_MAGIC = 0xFB10

VERT_FORMAT = 0x80004001
INDX_STRIDE = 2

PRIM_TRIANGLE = 0

MATS_ALPHA_TEST = 1 << 0
MATS_DEPTH_TEST = 1 << 1
MATS_BACKFACE_CULLING = 1 << 3
MATS_TEXTURING = 1 << 5

MATS_FUNC_GREATER = 4
MATS_FUNC_LESS_EQUAL = 3

MATS_BLEND_ZERO = 0
MATS_BLEND_ONE = 1

WRAP_REPEAT = 3
MAG_NEAREST = 0
MIN_NEAREST_NO_MIPMAP = 0

PLAYMODE_LOOPING = 3


# ---------------------------------------------------------------------------
# Binary helpers
# ---------------------------------------------------------------------------

def u16(v: int) -> bytes:
    return struct.pack("<H", v & 0xFFFF)


def i16(v: int) -> bytes:
    return struct.pack("<h", v)


def u32(v: int) -> bytes:
    return struct.pack("<I", v & 0xFFFFFFFF)


def f32(v: float) -> bytes:
    return struct.pack("<f", float(v))


def named_string(name: str | None, *, short: bool = False) -> bytes:
    """
    S3D string form used by scdbpf:
    - ordinary strings: one-byte length including trailing NUL
    - ANIM names: two-byte short length
    """
    if not name:
        return b"\x00\x00" if short else b"\x00"

    raw = name.encode("ascii", errors="replace")[:254]
    if short:
        return bytes((len(raw) + 1, 0)) + raw + b"\x00"
    return bytes((len(raw) + 1,)) + raw + b"\x00"


