# Minimal DXT1 encoder
# ---------------------------------------------------------------------------

def rgb_to_565(
    red: int,
    green: int,
    blue: int,
) -> int:
    r5 = (red * 31 + 127) // 255
    g6 = (green * 63 + 127) // 255
    b5 = (blue * 31 + 127) // 255

    return (
        (r5 << 11)
        | (g6 << 5)
        | b5
    )


def rgb_from_565(
    value: int,
) -> tuple[int, int, int]:
    r5 = (value >> 11) & 31
    g6 = (value >> 5) & 63
    b5 = value & 31

    return (
        (r5 << 3) | (r5 >> 2),
        (g6 << 2) | (g6 >> 4),
        (b5 << 3) | (b5 >> 2),
    )


def color_distance_sq(
    a: tuple[int, int, int],
    b: tuple[int, int, int],
) -> int:
    dr = a[0] - b[0]
    dg = a[1] - b[1]
    db = a[2] - b[2]

    return (
        dr * dr
        + dg * dg
        + db * db
    )


def choose_block_endpoints(
    colors: list[tuple[int, int, int, int]],
) -> tuple[int, int]:
    """
    Small dependency-free endpoint approximation.

    This is intentionally simpler than jsquish. It is meant to prove the
    Python-only pipeline, not to match fshgen's DXT compressor byte-for-byte.
    """
    opaque = [
        (red, green, blue)
        for red, green, blue, alpha in colors
        if alpha >= 128
    ]

    if not opaque:
        return 0, 0

    candidates: set[
        tuple[int, int, int]
    ] = set()

    for channel in range(3):
        candidates.add(
            min(
                opaque,
                key=lambda color: color[channel],
            )
        )

        candidates.add(
            max(
                opaque,
                key=lambda color: color[channel],
            )
        )

    candidate_list = list(candidates)

    best_a = candidate_list[0]
    best_b = candidate_list[0]
    best_distance = -1

    for color_a in candidate_list:
        for color_b in candidate_list:
            distance = color_distance_sq(
                color_a,
                color_b,
            )

            if distance > best_distance:
                best_a = color_a
                best_b = color_b
                best_distance = distance

    return (
        rgb_to_565(*best_a),
        rgb_to_565(*best_b),
    )


def dxt1_palette(
    color0: int,
    color1: int,
) -> list[tuple[int, int, int, int]]:
    rgb0 = rgb_from_565(color0)
    rgb1 = rgb_from_565(color1)

    if color0 > color1:
        return [
            (*rgb0, 255),
            (*rgb1, 255),
            (
                (2 * rgb0[0] + rgb1[0]) // 3,
                (2 * rgb0[1] + rgb1[1]) // 3,
                (2 * rgb0[2] + rgb1[2]) // 3,
                255,
            ),
            (
                (rgb0[0] + 2 * rgb1[0]) // 3,
                (rgb0[1] + 2 * rgb1[1]) // 3,
                (rgb0[2] + 2 * rgb1[2]) // 3,
                255,
            ),
        ]

    return [
        (*rgb0, 255),
        (*rgb1, 255),
        (
            (rgb0[0] + rgb1[0]) // 2,
            (rgb0[1] + rgb1[1]) // 2,
            (rgb0[2] + rgb1[2]) // 2,
            255,
        ),
        (0, 0, 0, 0),
    ]


def encode_dxt1_block(
    colors: list[tuple[int, int, int, int]],
) -> bytes:
    has_transparency = any(
        alpha < 128
        for _, _, _, alpha in colors
    )

    color0, color1 = choose_block_endpoints(
        colors
    )

    if has_transparency:
        # DXT1 1-bit-alpha mode.
        if color0 > color1:
            color0, color1 = color1, color0

    else:
        # DXT1 opaque four-color mode.
        if color0 < color1:
            color0, color1 = color1, color0

        elif color0 == color1:
            if color0 < 0xFFFF:
                color0 += 1

            elif color1 > 0:
                color1 -= 1

    palette = dxt1_palette(
        color0,
        color1,
    )

    packed_indices = 0

    for pixel_index, (
        red,
        green,
        blue,
        alpha,
    ) in enumerate(colors):

        if (
            has_transparency
            and alpha < 128
        ):
            palette_index = 3

        else:
            choices = (
                range(3)
                if color0 <= color1
                else range(4)
            )

            palette_index = min(
                choices,
                key=lambda idx: color_distance_sq(
                    (red, green, blue),
                    palette[idx][:3],
                ),
            )

        packed_indices |= (
            (palette_index & 3)
            << (2 * pixel_index)
        )

    return (
        u16(color0)
        + u16(color1)
        + u32(packed_indices)
    )


def encode_dxt1(
    image: Image.Image,
) -> bytes:
    image = image.convert("RGBA")
    width, height = image.size

    if width % 4 or height % 4:
        raise ValueError(
            "DXT1 requires width and height divisible by 4; "
            f"got {width}x{height}"
        )

    pixels = image.load()
    out = bytearray()

    for block_y in range(
        0,
        height,
        4,
    ):
        for block_x in range(
            0,
            width,
            4,
        ):
            block = [
                pixels[
                    block_x + x,
                    block_y + y,
                ]
                for y in range(4)
                for x in range(4)
            ]

            out += encode_dxt1_block(
                block
            )

    return bytes(out)


