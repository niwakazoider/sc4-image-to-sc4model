@dataclass(frozen=True)
class ObjRef:
    vertex: int
    texcoord: int


@dataclass
class ObjMesh:
    material: str
    object_name: str | None
    faces: list[tuple[ObjRef, ObjRef, ObjRef]] = field(default_factory=list)


@dataclass
class ObjModel:
    vertices: list[tuple[float, float, float]]
    texcoords: list[tuple[float, float]]
    meshes: list[ObjMesh]


def resolve_obj_index(text: str, count: int) -> int:
    idx = int(text)

    if idx == 0:
        raise ValueError("OBJ indices are 1-based; index 0 is invalid")

    if idx > 0:
        return idx - 1

    return count + idx


def parse_obj(path: Path) -> ObjModel:
    """
    Parse the limited OBJ dialect generated by the BAT script.

    Supported:
    - v
    - vt
    - o
    - g
    - usemtl
    - triangular f entries containing v/vt or v/vt/vn

    Normals are ignored. Vertices are later reindexed by (v, vt), matching the
    behavior needed for the generated BAT OBJ files.
    """
    vertices: list[tuple[float, float, float]] = []
    texcoords: list[tuple[float, float]] = []
    meshes: list[ObjMesh] = []

    object_name: str | None = None
    current_material = ""
    current_mesh: ObjMesh | None = None

    def ensure_mesh() -> ObjMesh:
        nonlocal current_mesh

        if current_mesh is None:
            current_mesh = ObjMesh(
                material=current_material,
                object_name=object_name,
            )
            meshes.append(current_mesh)

        return current_mesh

    lines = path.read_text(
        encoding="utf-8",
        errors="replace",
    ).splitlines()

    for lineno, line in enumerate(lines, 1):
        line = line.strip()

        if not line or line.startswith("#"):
            continue

        parts = line.split()
        op = parts[0]

        if op == "v":
            if len(parts) < 4:
                raise ValueError(
                    f"{path}:{lineno}: malformed vertex"
                )

            vertices.append(
                (
                    float(parts[1]),
                    float(parts[2]),
                    float(parts[3]),
                )
            )

        elif op == "vt":
            if len(parts) < 3:
                raise ValueError(
                    f"{path}:{lineno}: malformed texture coordinate"
                )

            texcoords.append(
                (
                    float(parts[1]),
                    float(parts[2]),
                )
            )

        elif op == "o":
            object_name = (
                " ".join(parts[1:])
                if len(parts) > 1
                else None
            )
            current_mesh = None

        elif op == "g":
            # The BAT generator writes both o and g.
            # Object names are sufficient for the S3D ANIM name.
            continue

        elif op == "usemtl":
            current_material = (
                " ".join(parts[1:])
                if len(parts) > 1
                else ""
            )
            current_mesh = None

        elif op == "f":
            refs: list[ObjRef] = []

            for token in parts[1:]:
                bits = token.split("/")

                if (
                    len(bits) < 2
                    or not bits[0]
                    or not bits[1]
                ):
                    raise ValueError(
                        f"{path}:{lineno}: every face vertex "
                        "must contain v/vt"
                    )

                vi = resolve_obj_index(
                    bits[0],
                    len(vertices),
                )
                ti = resolve_obj_index(
                    bits[1],
                    len(texcoords),
                )

                refs.append(
                    ObjRef(
                        vertex=vi,
                        texcoord=ti,
                    )
                )

            if len(refs) != 3:
                raise ValueError(
                    f"{path}:{lineno}: only triangulated faces "
                    f"are supported; got {len(refs)} vertices"
                )

            ensure_mesh().faces.append(
                (
                    refs[0],
                    refs[1],
                    refs[2],
                )
            )

        elif op in (
            "vn",
            "s",
            "mtllib",
        ):
            continue

        else:
            # Ignore comments / metadata unknown to this minimal parser.
            continue

    meshes = [
        mesh
        for mesh in meshes
        if mesh.faces
    ]

    if not vertices:
        raise ValueError(
            f"{path}: OBJ has no vertices"
        )

    if not texcoords:
        raise ValueError(
            f"{path}: OBJ has no texture coordinates"
        )

    if not meshes:
        raise ValueError(
            f"{path}: OBJ has no triangle meshes"
        )

    return ObjModel(
        vertices=vertices,
        texcoords=texcoords,
        meshes=meshes,
    )


