#!/usr/bin/env python3
"""
mini_fshgen.py
==============

Experimental BAT-focused Python subset of memo33/fshgen.

Implemented:
- Wavefront OBJ -> SimCity 4 S3D v1.5
- PNG/BMP -> single-image FSH using DXT1
- IID extraction from filenames
- DBPF 1.0 / .SC4Model writing
- QFS/RefPack compression + DIR resource generation

Not implemented:
- export
- DXT3/DXT5
- mipmaps
- slicing/layer composition
- separate alpha files
- darken/brighten
- QFS/RefPack compression
- append mode
- general-purpose OBJ features beyond triangulated v/vt faces

DBPF resources are QFS/RefPack-compressed when compression saves enough space.
A standard DBPF DIR resource is generated automatically for compressed entries.

This is a BAT-only prototype, not a drop-in replacement for all fshgen features.
"""

