# DBPF writer
# ---------------------------------------------------------------------------

@dataclass
class DbpfEntry:
    tid: int
    gid: int
    iid: int
    data: bytes
    decompressed_size: int | None = None


def write_dbpf(
    path: Path,
    entries: Sequence[DbpfEntry],
) -> None:
    """
    Write DBPF 1.0 with QFS compression where useful.

    Compressed resources are listed in one standard DIR resource:
      E86B1EEF / E86B1EEF / 286B1F03

    The DIR resource itself is stored uncompressed.
    """
    packed_entries: list[DbpfEntry] = []

    for entry in entries:
        raw = bytes(entry.data)
        packed = qfs_compress(raw)

        if packed != raw:
            packed_entries.append(
                DbpfEntry(
                    tid=entry.tid,
                    gid=entry.gid,
                    iid=entry.iid,
                    data=packed,
                    decompressed_size=len(raw),
                )
            )
        else:
            packed_entries.append(
                DbpfEntry(
                    tid=entry.tid,
                    gid=entry.gid,
                    iid=entry.iid,
                    data=raw,
                    decompressed_size=None,
                )
            )

    compressed_entries = [
        entry
        for entry in packed_entries
        if entry.decompressed_size is not None
    ]

    if compressed_entries:
        packed_entries.append(
            DbpfEntry(
                tid=TID_DIR,
                gid=GID_DIR,
                iid=IID_DIR,
                data=build_dir_resource(
                    compressed_entries
                ),
                decompressed_size=None,
            )
        )

    # Keep deterministic ordering, including the DIR entry.
    packed_entries.sort(
        key=lambda entry: (
            entry.tid,
            entry.gid,
            entry.iid,
        )
    )

    header = bytearray(96)
    header[0:4] = b"DBPF"

    struct.pack_into("<I", header, 4, 1)
    struct.pack_into("<I", header, 8, 0)

    now = int(time.time()) & 0xFFFFFFFF
    struct.pack_into("<I", header, 24, now)
    struct.pack_into("<I", header, 28, now)

    struct.pack_into("<I", header, 32, 7)

    payload = bytearray()
    index = bytearray()
    cursor = 96

    for entry in packed_entries:
        data = bytes(entry.data)

        index += struct.pack(
            "<IIIII",
            entry.tid & 0xFFFFFFFF,
            entry.gid & 0xFFFFFFFF,
            entry.iid & 0xFFFFFFFF,
            cursor,
            len(data),
        )

        payload += data
        cursor += len(data)

    index_offset = 96 + len(payload)

    struct.pack_into(
        "<I",
        header,
        36,
        len(packed_entries),
    )
    struct.pack_into(
        "<I",
        header,
        40,
        index_offset,
    )
    struct.pack_into(
        "<I",
        header,
        44,
        len(index),
    )

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    path.write_bytes(
        bytes(header)
        + bytes(payload)
        + bytes(index)
    )

    raw_total = sum(
        len(entry.data)
        if entry.decompressed_size is None
        else entry.decompressed_size
        for entry in packed_entries
        if entry.tid != TID_DIR
    )

    stored_total = sum(
        len(entry.data)
        for entry in packed_entries
        if entry.tid != TID_DIR
    )

    print(
        f"QFS: {len(compressed_entries)} compressed entries; "
        f"resource bytes {raw_total:,} -> {stored_total:,}"
    )


